using System;
using System.Linq;
using FootballRpg.Simulation;
using UnityEngine;

namespace FootballRpg.Presentation
{
    public sealed partial class LaunchScreen
    {
        private bool calendarOpen, showTrainingResults;
        private int calendarReadyFrame;
        private string trainingFocus;
        private bool interactiveTraining, coachDiscussion;
        private PracticeFamily practiceFamily;
        private Vector2 trainingScroll;
        private string calendarSelection, calendarError;
        private CalendarChoice calendarChoice;
        private Vector2 calendarScroll, impactScroll, activityScroll, readinessScroll;
        private GUIStyle calendarText;
        public void OpenCalendar()
        {
            if (Career?.Calendar == null) return;
            if (Career.Week.CalendarBlock != null) { calendarOpen = false; return; }
            practiceFamily = GuidedPracticeSession.Recommended(Career.UserPlayer.PrimaryPositionId);
            calendarReadyFrame = Time.frameCount + 1;
            calendarOpen = true; calendarChoice = null; calendarError = null;
            calendarSelection = Career.Calendar.CurrentCommitments.FirstOrDefault()?.Id;
        }
        private void PreviewCalendar(CalendarChoiceKind kind, string id = null)
        {
            try
            {
                calendarChoice = Career.Calendar.Preview(kind, id);
                if (calendarChoice.Focus != null) calendarChoice = Career.Calendar.Preview(kind, id, trainingFocus, interactiveTraining ? (PracticeFamily?)practiceFamily : null);
                calendarError = null;
            }
            catch (Exception e) when (e is ArgumentException || e is InvalidOperationException)
            { calendarChoice = null; calendarError = e.Message; }
        }
        private void ConfirmCalendar()
        {
            if (calendarChoice == null) return;
            int before = Career.Training.Results.Count;
            Career.Calendar.Commit(calendarChoice); calendarChoice = null;
            if (Career.Training.Results.Count > before) { showTrainingResults = true; trainingScroll = Vector2.zero; }
            calendarSelection = Career.Calendar.CurrentCommitments.FirstOrDefault()?.Id;
            if (Career.Week.Phase == CareerWeekPhase.FixtureReady) { calendarOpen = false; returnToClub = false; }
            if (Career.Calendar.AwaitingMeeting) OpenMeetings();
            if (Career.Calendar.AwaitingPractice)
            {
                practiceView = new GameObject("Guided Practice").AddComponent<GuidedPracticeView>();
                practiceView.Initialize(Career, () => { practiceView = null; showTrainingResults = true; trainingScroll = Vector2.zero; });
            }
        }
        private void CycleTrainingFocus()
        {
            if (interactiveTraining) { practiceFamily = (PracticeFamily)(((int)practiceFamily + 1) % 4); calendarChoice = null; calendarError = null; return; }
            var focuses = Career.Calendar.TrainingFocuses;
            int current = Array.FindIndex(focuses.ToArray(), f => f.Id == trainingFocus);
            trainingFocus = current + 1 < focuses.Count ? focuses[current + 1].Id : null;
            calendarChoice = null; calendarError = null;
        }
        private void UpdateCalendar()
        {
            if (Time.frameCount <= calendarReadyFrame) return;
            var previouslyShown = calendarChoice;
            if (Input.GetKeyDown(KeyCode.Escape)) { CloseCalendar(); return; }
            if (Input.GetKeyDown(KeyCode.F)) CycleTrainingFocus();
            if (Input.GetKeyDown(KeyCode.I)) ToggleTrainingMode();
            if (Input.GetKeyDown(KeyCode.D)) coachDiscussion = !coachDiscussion;
            if (Input.GetKeyDown(KeyCode.T)) showTrainingResults = true;
            if (Input.GetKeyDown(KeyCode.R)) showTrainingResults = false;
            if (Input.GetKeyDown(KeyCode.Tab))
            {
                var current = Career.Calendar.CurrentCommitments;
                if (current.Count > 0) calendarSelection = current[(Array.FindIndex(current.ToArray(), c => c.Id == calendarSelection) + 1) % current.Count].Id;
                calendarChoice = null;
            }
            if (Input.GetKeyDown(KeyCode.Alpha1)) PreviewCalendar(CalendarChoiceKind.Attend, calendarSelection);
            if (Input.GetKeyDown(KeyCode.Alpha2)) PreviewCalendar(CalendarChoiceKind.Skip, calendarSelection);
            if (Input.GetKeyDown(KeyCode.Alpha3)) PreviewCalendar(CalendarChoiceKind.Wait);
            var options = Career.Calendar.Activities.Where(a => a.Selectable).ToArray();
            for (int i = 0; i < options.Length && i < 6; i++)
                if (Input.GetKeyDown((KeyCode)((int)KeyCode.Alpha4 + i)))
                    PreviewCalendar(options[i].ExtraPractice ? CalendarChoiceKind.ExtraPractice : CalendarChoiceKind.Replace, options[i].Id);
            // Never confirm a choice generated by another key in the same frame.
            if (Input.GetKeyDown(KeyCode.Return) && calendarChoice == previouslyShown) ConfirmCalendar();
        }
        private void ToggleTrainingMode() { interactiveTraining = !interactiveTraining; calendarChoice = null; calendarError = null; }
        private void DrawCalendar()
        {
            var calendar = Career.Calendar;
            if (calendarText == null) calendarText = new GUIStyle(GUI.skin.label) { fontSize = 18, wordWrap = true };
            GUI.Label(new Rect(50, 35, 900, 40), "YOUR WEEK  ·  " + calendar.TimeLabel(calendar.Minute), body);
            var player = Career.UserPlayer;
            GUI.Label(new Rect(50, 85, 1300, 30), $"Fatigue {player.Fatigue:P0}  ·  Confidence {player.Confidence:P0}  ·  Morale {player.Morale:P0}  ·  Injury: {player.InjuryDaysRemaining} day(s)  ·  Training yield {Career.Readiness.TrainingMultiplier(player.Id):P0}", calendarText);
            GUI.Label(new Rect(50, 120, 1300, 25), Career.Week.Active ? "Inspect freely; confirm to spend time. Attend Sunday’s fixture to play; skipped fixtures continue without you." : "Sample calendar. Start a new career to connect character creation, the week and Sunday’s fixture.", small);
            GUI.Label(new Rect(50, 155, 720, 30), "COMMITMENTS  ·  Select a row, or Tab between current commitments", eyebrow);
            calendarScroll = GUI.BeginScrollView(new Rect(50, 200, 725, 330), calendarScroll, new Rect(0, 0, 700, calendar.Commitments.Count * 78));
            for (int i = 0; i < calendar.Commitments.Count; i++)
            {
                var c = calendar.Commitments[i]; var result = calendar.ResultFor(c.Id);
                string state = result?.Fact.Attendance.ToString() ?? (calendar.CurrentCommitments.Contains(c) ? "NOW" : "Upcoming");
                if (GUI.Button(new Rect(0, i * 78, 695, 70), (calendarSelection == c.Id ? "• " : "") + calendar.TimeLabel(c.StartMinute) + "  /  " + c.Activity.Name + "\n" +
                    (c.Required ? "Required" : "Optional") + " · " + c.Activity.DurationSlots + " slot(s) · " + state, button))
                { calendarSelection = c.Id; calendarChoice = null; calendarError = null; }
            }
            GUI.EndScrollView();
            if (GUI.Button(new Rect(50, 550, 340, 35), "READINESS CHANGES  [R]", button)) showTrainingResults = false;
            if (GUI.Button(new Rect(410, 550, 340, 35), "TRAINING RESULTS  [T]", button)) showTrainingResults = true;
            if (showTrainingResults)
            {
                string reports = Career.Training.Results.Count == 0 ? "No training completed yet." : string.Join("\n\n", Career.Training.Results.Reverse().Take(20).Select(TrainingExplanation));
                float height = Mathf.Max(210, calendarText.CalcHeight(new GUIContent(reports), 680));
                trainingScroll = GUI.BeginScrollView(new Rect(50, 600, 725, 210), trainingScroll, new Rect(0, 0, 700, height));
                GUI.Label(new Rect(0, 0, 680, height), reports, calendarText); GUI.EndScrollView();
            }
            else
            {
                var recent = Career.Readiness.Changes.Where(c => c.PlayerId == player.Id).Reverse().Take(100).ToArray();
                readinessScroll = GUI.BeginScrollView(new Rect(50, 600, 725, 210), readinessScroll, new Rect(0, 0, 700, Math.Max(50, recent.Length * 60)));
                if (recent.Length == 0) GUI.Label(new Rect(0, 0, 690, 50), "No changes yet. Inspecting the schedule never changes readiness.", calendarText);
                for (int i = 0; i < recent.Length; i++)
                    GUI.Label(new Rect(0, i * 60, 690, 58), ReadinessExplanation(recent[i]), calendarText);
                GUI.EndScrollView();
            }
            var alternatives = calendar.Activities.Where(a => a.Selectable).ToArray();
            activityScroll = GUI.BeginScrollView(new Rect(830, 155, 565, 260), activityScroll, new Rect(0, 0, 540, (3 + alternatives.Length) * 44));
            GUI.enabled = !calendar.Finished;
            if (GUI.Button(new Rect(0, 0, 530, 38), "ATTEND SELECTED  [1]", button)) PreviewCalendar(CalendarChoiceKind.Attend, calendarSelection);
            if (GUI.Button(new Rect(0, 44, 530, 38), "SKIP SELECTED  [2]", button)) PreviewCalendar(CalendarChoiceKind.Skip, calendarSelection);
            if (GUI.Button(new Rect(0, 88, 530, 38), "WAIT TO NEXT SLOT  [3]", button)) PreviewCalendar(CalendarChoiceKind.Wait);
            for (int i = 0; i < alternatives.Length; i++)
            {
                var activity = alternatives[i];
                if (GUI.Button(new Rect(0, (i + 3) * 44, 530, 38), activity.Name + (i < 6 ? "  [" + (i + 4) + "]" : ""), button))
                    PreviewCalendar(activity.ExtraPractice ? CalendarChoiceKind.ExtraPractice : CalendarChoiceKind.Replace, activity.Id);
            }
            GUI.enabled = true; GUI.EndScrollView();
            string focusName = Career.Calendar.TrainingFocuses.SingleOrDefault(f => f.Id == trainingFocus)?.Name ?? (Career.Calendar.TrainingFocuses.SingleOrDefault(f => f.Id == Career.Meetings.PreferredTrainingFocusId)?.Name + (Career.Meetings.PreferredTrainingFocusId == null ? "Scheduled focus" : " (career plan)"));
            if (GUI.Button(new Rect(830, 425, 530, 38), "FOCUS: " + (interactiveTraining ? practiceFamily.ToString() : focusName) + "  [F]", button)) CycleTrainingFocus();
            if (GUI.Button(new Rect(830, 470, 330, 38), (interactiveTraining ? "GUIDED PRACTICE" : "SIMULATED TRAINING") + "  [I]", button)) ToggleTrainingMode();
            if (GUI.Button(new Rect(1170, 470, 190, 38), "COACH  [D]", button)) coachDiscussion = !coachDiscussion;
            string explanation = calendarError ?? (calendar.Finished ? "Week complete. All attendance decisions are recorded." : "Choose an activity to inspect its time cost and attendance consequences.");
            if (calendarChoice == null && Career.Week.SelectionAnnouncement != null)
                explanation += "\n\nSelection briefing: " + Career.Week.SelectionAnnouncement.Outcome + " · " + Career.Week.SelectionAnnouncement.Reason + "\n\n" + Career.Week.Preparation;
            if (calendarChoice != null)
            {
                var p = calendarChoice;
                explanation = p.Kind + (p.Activity == null ? "" : ": " + p.Activity.Name) + "\nCost: " + p.CostMinutes + " minutes (" + (p.CostMinutes / (float)calendar.MinutesPerSlot).ToString("0.##") + " slots)\n" +
                    "Ends: " + calendar.TimeLabel(p.EndMinute) + "\nKnown delay: " + (p.EndMinute - p.ActivityEndMinute) + " minutes\n\n" +
                    (p.Impacts.Count == 0 ? "No scheduled commitments affected." : string.Join("\n", p.Impacts.Select(i => i.Commitment.Activity.Name + " (" + (i.Commitment.Required ? "required" : "optional") + "): " + i.Outcome + (i.LateMinutes > 0 ? " by " + i.LateMinutes + " min" : ""))));
            }
            if (calendarChoice != null)
            {
                var a = calendarChoice.Activity;
                double slots = (calendarChoice.ActivityEndMinute - calendarChoice.StartMinute) / (double)calendar.MinutesPerSlot;
                double fatigue = a == null ? -Career.Readiness.Rules.IdleRecoveryPerSlot * slots : a.Training && player.InjuryDaysRemaining > 0 ? 0 : a.FatiguePerSlot * slots;
                explanation += $"\n\nWorkload: fatigue {fatigue * 100:+0.#;-0.#;0} points (clamped to 0–100).";
                if (a?.Training == true) explanation += $"\nTraining yield at current readiness: {Career.Readiness.TrainingMultiplier(player.Id):P0} × {slots:0.##} slot(s).";
                if (a != null && !(a.Training && player.InjuryDaysRemaining > 0)) explanation += $"\nActivity morale: {a.MoralePerSlot * slots * 100:+0.#;-0.#;0} points.";
                explanation += "\nMissed required commitments reduce morale; late attendance reduces it less. Injury recovery follows elapsed career days.";
            }
            if (calendarChoice != null)
                foreach (var impact in calendarChoice.Impacts)
                {
                    var meeting = Career.Meetings.Meetings.SingleOrDefault(m => m.CommitmentId == impact.Commitment.Id);
                    if (meeting != null) explanation += "\n\n" + meeting.Role + " meeting: " + EffectText(impact.Outcome == AttendanceOutcome.Skipped ? meeting.Skipped : impact.Outcome == AttendanceOutcome.Late ? meeting.Late : meeting.Attended) +
                        (impact.Outcome == AttendanceOutcome.Skipped ? ". Existing plans stay unchanged." : ". Attending opens a conversation after the slot is committed.");
                }
            if (calendarChoice?.Activity?.Id == "selection" || calendarChoice?.Activity?.Id == "match-preparation" || calendarChoice?.Activity?.Id == "match")
                explanation += "\n\nMATCH PLAN\n" + Career.Week.Preparation;
            if (calendarChoice?.Focus != null)
                explanation += "\n\nTRAINING PREVIEW\n" + TrainingExplanation(Career.Training.Preview(calendarChoice));
            if (interactiveTraining) explanation += "\n\nThree paused decisions replace the simulated reward. Only completed drills earn XP; failed drills earn 65%. The estimate assumes successful first-option actions. Ending early does not refund the slot.";
            if (coachDiscussion) explanation = "TRAINING DIRECTION\nCoach recommends " + GuidedPracticeSession.Recommended(player.PrimaryPositionId) + " for " + player.PrimaryPositionId.ToUpperInvariant() + ". You may practice any family.\n" + GuidedPracticeSession.Guidance(practiceFamily) + "\n\nChoose guided practice [I], then change direction [F]. Simulated attendance spreads XP across your chosen focus and position; guided attendance concentrates it on the actions you take.\n\n" + explanation;
            float textHeight = Mathf.Max(235, calendarText.CalcHeight(new GUIContent(explanation), 520));
            impactScroll = GUI.BeginScrollView(new Rect(830, 520, 565, 240), impactScroll, new Rect(0, 0, 535, textHeight));
            GUI.Label(new Rect(0, 0, 520, textHeight), explanation, calendarText); GUI.EndScrollView();
            if (GUI.Button(new Rect(50, 830, 300, 45), (returnToClub ? "BACK TO CLUB" : "BACK") + "  [ESC]", button)) CloseCalendar();
            GUI.enabled = calendarChoice != null && Time.frameCount > calendarReadyFrame;
            if (GUI.Button(new Rect(990, 800, 380, 60), "CONFIRM CHOICE  [ENTER]", button)) ConfirmCalendar();
            GUI.enabled = true;
        }
        private static string TrainingExplanation(TrainingReport report) =>
            report.FocusName + $" — {report.TotalXp:0.0} XP" +
            $"\nBase {report.BaseXp:0.#} XP × {report.ParticipatedSlots:0.##} slot(s) × readiness {report.ReadinessMultiplier:0.###}" +
            $"\nCoach ×{report.CoachMultiplier:0.##} · Staff ×{report.StaffMultiplier:0.##} · Facilities ×{report.FacilityMultiplier:0.##}" +
            "\n" + string.Join("\n", report.Gains.Select(g => g.SkillId.Replace('-', ' ') + $": +{g.Xp:0.0} XP · share {g.Share:P0} · level ×{g.LevelMultiplier:0.##}" +
                (g.PreviousLevel == g.NewLevel ? $" · level {g.NewLevel}" : $" · {g.PreviousLevel} → {g.NewLevel}")));
        private static string ReadinessExplanation(ReadinessChange c) => c.Reason + $"\nFatigue {c.FatigueDelta * 100:+0.#;-0.#;0} · Confidence {c.ConfidenceDelta * 100:+0.#;-0.#;0} · Morale {c.MoraleDelta * 100:+0.#;-0.#;0}" + (c.InjuryDaysDelta == 0 ? "" : $" · Injury days {c.InjuryDaysDelta:+0;-0}");
        private void VerifyCalendar()
        {
            var original = Career;
            try
            {
                Career = FootballRpg.Content.PrototypeContent.CreateCareer();
                for (int i = 0; i < 10; i++) OpenCalendar();
                if (Career.Calendar.Minute != 0) throw new InvalidOperationException("Calendar navigation advanced time.");
                PreviewCalendar(CalendarChoiceKind.Attend, "mon-training");
                if (calendarChoice?.CostMinutes != 360 || Career.Calendar.Minute != 0) throw new InvalidOperationException("Calendar preview failed.");
                trainingFocus = "passing"; PreviewCalendar(CalendarChoiceKind.Attend, "mon-training");
                var trainingPreview = Career.Training.Preview(calendarChoice);
                float initialFatigue = Career.UserPlayer.Fatigue;
                ConfirmCalendar(); ConfirmCalendar();
                if (Career.UserPlayer.Fatigue <= initialFatigue || Career.Readiness.Training.Count != 1) throw new InvalidOperationException("Training readiness not connected.");
                if (Career.Training.Results.Count != 1 || Career.Training.Results[0].FocusName != "Passing and possession" ||
                    Math.Abs(Career.Training.Results[0].TotalXp - trainingPreview.TotalXp) > .00001)
                    throw new InvalidOperationException("Training focus/preview/award mismatch.");
                PreviewCalendar(CalendarChoiceKind.ExtraPractice, "extra-practice"); ConfirmCalendar();
                if (Career.Calendar.Minute != 720 || Career.Calendar.Attendance.Count != 2) throw new InvalidOperationException("Extra practice timing failed.");
                PreviewCalendar(CalendarChoiceKind.Skip, "mon-media"); ConfirmCalendar();
                PreviewCalendar(CalendarChoiceKind.Replace, "party");
                if (calendarChoice?.Impacts.Single().Outcome != AttendanceOutcome.Late) throw new InvalidOperationException("Missing lateness warning.");
                ConfirmCalendar(); PreviewCalendar(CalendarChoiceKind.Attend, "tue-training"); ConfirmCalendar();
                var result = Career.Calendar.ResultFor("tue-training");
                if (result.Fact.Attendance != AttendanceOutcome.Late || result.LateMinutes != 60 || result.ParticipatedMinutes != 300)
                    throw new InvalidOperationException("Calendar late attendance failed.");
                float tired = Career.UserPlayer.Fatigue;
                PreviewCalendar(CalendarChoiceKind.Replace, "rest"); ConfirmCalendar();
                if (Career.UserPlayer.Fatigue >= tired || Career.Readiness.Changes.Count == 0 || Career.Readiness.Training.Count != 3)
                    throw new InvalidOperationException("Recovery/readiness recording failed.");
                if (Career.Training.Results.Count != 3 || Career.Training.Results.Any(t => t.TotalXp <= 0)) throw new InvalidOperationException("Training attendance rewards failed.");
                Debug.Log("FOOTBALL_RPG_TRAINING_PASSED");
                Debug.Log("FOOTBALL_RPG_READINESS_PASSED");
                Debug.Log("FOOTBALL_RPG_CALENDAR_PASSED");
            }
            finally { Career = original; calendarOpen = false; calendarChoice = null; trainingFocus = null; showTrainingResults = false; }
        }
    }
}
